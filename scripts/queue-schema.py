#!/usr/bin/env python3
"""Embed the repository-local v1 device queue, or check committed copies."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
create = (root / "protocol/queue.sql").read_text().rstrip()
upgrade = (root / "protocol/queue-upgrade.sql").read_text().rstrip()
version = re.search(r"`PRAGMA user_version = (\d+)`", create).group(1)
notice = "Generated by scripts/queue-schema.py; edit protocol/queue.sql and protocol/queue-upgrade.sql."
indent = lambda text: "\n".join("    " + line if line else "" for line in text.splitlines())
outputs = {}
if (root / "Sources").exists():
    outputs["Sources/ClickMan/QueueSchema.swift"] = f'''// {notice}
enum QueueSchema {{
    static let format = {version}

    static let create = """
{indent(create)}
    """

    static let upgrade = """
{indent(upgrade)}
    """
}}
'''
elif (root / "libraries").exists():
    outputs["libraries/clickman/src/main/kotlin/com/lockvoid/clickman/QueueSchema.kt"] = f'''// {notice}
package com.lockvoid.clickman

internal object QueueSchema {{
    const val FORMAT = {version}

    val create: String = """
{indent(create)}
    """.trimIndent()

    val upgrade: String = """
{indent(upgrade)}
    """.trimIndent()
}}
'''
else:
    outputs["crates/clickman/src/queue_schema.rs"] = f'''// {notice}
pub(crate) const FORMAT: i64 = {version};
pub(crate) const CREATE: &str = include_str!("queue.sql");
pub(crate) const UPGRADE: &str = include_str!("queue-upgrade.sql");
'''
    outputs["crates/clickman/src/queue.sql"] = create + "\n"
    outputs["crates/clickman/src/queue-upgrade.sql"] = upgrade + "\n"
stale = []
for relative, content in outputs.items():
    path = root / relative
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            stale.append(relative)
    else:
        path.write_text(content)
if stale:
    raise SystemExit("Queue schema copies differ: " + ", ".join(stale))
print("Queue schema copies match protocol/." if "--check" in sys.argv else "Queue schema copies generated.")
